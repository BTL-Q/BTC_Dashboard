"""홈 — 무엇을 재는지, 어디서 무엇을 보는지."""

from __future__ import annotations

import streamlit as st

from core.theme import short
from core.ui import get_context

ctx = get_context()

st.title("🧲 코인 영향력 분석")
st.caption(
    "시장모형 회귀 `r_i = α + β·r_m + ε` — 선택한 기준 코인에 다른 코인이 얼마나 끌려다니는지 숫자로"
)

st.markdown(
    f"""
    왼쪽 사이드바에서 **기준 코인 · 봉 · 기간**을 고르면 모든 페이지에 함께 적용됩니다.
    지금은 **{ctx.market_label} · {ctx.timeframe} · {ctx.period_label}**
    ({len(ctx.rets):,}봉, {ctx.rets.index.min().date()} ~ {ctx.rets.index.max().date()}) 기준입니다.
    """
)

st.markdown("---")


# ======================================================================
# 지금 슬라이스 요약
# ======================================================================

follow = ctx.table.sort_values("r2", ascending=False)
top_m, top = str(follow.index[0]), follow.iloc[0]
low_m, low = str(follow.index[-1]), follow.iloc[-1]

c1, c2, c3 = st.columns(3)
c1.metric(f"{ctx.market_label} 추종 1위", short(top_m), f"R² {top['r2']:.0%}", delta_color="off")
c2.metric("가장 독립적", short(low_m), f"R² {low['r2']:.0%}", delta_color="off")
c3.metric("분석 대상", f"{len(ctx.results)}개 코인", f"{len(ctx.rets):,}봉", delta_color="off")

st.markdown("---")


# ======================================================================
# 무엇을 재는가
# ======================================================================

st.markdown("### 무엇을 재는가")

st.latex(r"r_{i,t} = \alpha + \beta \cdot r_{m,t} + \varepsilon_t")

st.markdown(
    f"""
    | 기호 | 의미 | 읽는 법 |
    |:---:|:---|:---|
    | **β** | 민감도 | {ctx.market_label}가 1% 움직일 때의 반응 폭 |
    | **R²** | 설명력 | 이 코인 움직임 중 {ctx.market_label}로 설명되는 비율 |
    | **α** | 초과수익 | {ctx.market_label}로 설명되지 않는 고유 수익 (연율) |
    | **σ_ε** | 고유 변동성 | {ctx.market_label}를 제거하고 남은 몫 — 분산투자로 줄일 수 있는 부분 |

    **β와 R²는 서로 독립입니다.** 크게 반응하는 것(β)과 충실하게 따라가는 것(R²)은
    다른 질문이고, 포트폴리오를 짤 때 실제로 중요한 건 후자입니다.
    """
)

st.markdown("---")


# ======================================================================
# 페이지 안내
# ======================================================================

st.markdown("### 어디서 무엇을 보나")

st.markdown(
    """
    | 페이지 | 답하는 질문 | 한 화면에 묶은 이유 |
    |:---|:---|:---|
    | **📊 전체 순위** | 누가 얼마나 따라가나 | 순위를 보고 곧바로 수치를 확인하게 |
    | **🔍 코인 상세** | 이 코인은 어떤가 | 지표·산점도·해석은 따로 보면 의미가 없어서 |
    | **📈 안정성** | 그 관계를 믿어도 되나 | β만 보면 크기만 알고, R²를 같이 봐야 일관성을 앎 |
    | **⏱ 예측력** | 설명인가 예측인가 | 프로파일·수수료 대조를 떼면 오독하기 쉬워서 |
    | **🔗 상관관계** | 여러 개 담으면 분산이 되나 | 행렬과 유효 종목 수를 함께 |
    """
)

st.markdown("---")


# ======================================================================
# 함정 노트
# ======================================================================

with st.expander("⚠️ 이 숫자를 투자에 쓰기 전에 — 체크할 것 5가지"):
    st.markdown(
        f"""
**1. 분산투자 확인.** 상관이나 R²가 높은 코인끼리는 여러 개 담아도 리스크가 많이 겹칩니다.
→ **🔗 상관관계** 페이지의 유효 종목 수를 보세요.

**2. β가 큰 코인은 양날입니다.** {ctx.market_label}가 오르면 더 크게 오르지만,
빠지면 더 크게 빠집니다. 상승 레버리지이자 하락 레버리지입니다.

**3. R²가 높으면 {ctx.market_label} 베팅에 가깝습니다.** 방향성을 {ctx.market_label}가 많이 결정합니다.
{ctx.market_label}를 이미 들고 있다면 중복 노출인지 확인해야 합니다.

**4. β와 R²는 고정값이 아닙니다.** 구간을 바꾸면 숫자가 달라집니다.
→ **📈 안정성** 페이지에서 얼마나 흔들리는지 확인하세요.

**5. 같은 봉 회귀는 예측이 아닙니다.** *같은 시점*의 두 수익률을 맞추는 것이라 설명이지 예측이 아닙니다.
→ **⏱ 예측력** 페이지가 실측으로 보여줍니다. 한 봉만 밀어도 설명력이 거의 사라집니다.
        """
    )

st.caption("학습·연구 목적입니다. 투자 조언이 아니며 어떤 수익도 보장하지 않습니다.")
